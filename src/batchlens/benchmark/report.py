"""The benchmark's numbers as the verification report (Markdown)."""

from __future__ import annotations

from typing import Any


def _share(found: int, of: int) -> str:
    return f"{found} of {of} ({100 * found / of:.1f} %)" if of else "none run"


def _days(spread: dict[str, float] | None) -> str:
    if spread is None:
        return "never found"
    return f"{spread['median']:.1f} (from {spread['min']:.1f} to {spread['max']:.1f})"


def render(result: dict[str, Any]) -> str:
    counts, settings, bad = result["counts"], result["settings"], result["bad_records"]
    lines = [
        "# Verification report",
        "",
        "Generated by `batchlens benchmark`; do not edit by hand. A test fails when this file is",
        "not what the command gives (`tests/test_benchmark.py`).",
        "",
        "## What this is, and is not",
        "",
        "The analysis of BatchLens run over many **synthetic** batches whose faults are known,",
        "counting what it found, what it missed and what it refused to answer. The batches come",
        "from the **same generator** as the demo, with one thing varied at a time, so this",
        "measures whether the analysis does what it says on data shaped like its own demo. It",
        "says nothing about real processes, real assay noise or real historians, and it is not a",
        "validation of anything.",
        "",
        f"- Generator: `{result['generator']}`, {settings['batches_per_variant']} seeds of every variant.",
        f"- Batches: {counts['normal']} normal, {counts['reduced_productivity']} with reduced specific",
        f"  productivity (from culture day {', '.join(f'{d:g}' for d in settings['onset_days'])}; to",
        f"  {', '.join(f'{100 * f:g} %' for f in settings['qp_factors'])} of nominal), {counts['reduced_recovery']} with",
        f"  reduced Protein A recovery ({', '.join(f'{100 * r:g} %' for r in settings['recoveries'])} against a",
        f"  nominal 92 %), {counts['bad_records']} badly recorded.",
        f"- Each is compared with {counts['references']} normal batches taken in turn as the reference:",
        f"  {counts['comparisons']} comparisons.",
        f"- Defaults in the app: titer tolerance {settings['titer_tolerance_default_percent']:g} %, recovery",
        f"  tolerance {settings['recovery_tolerance_default_points']:g} points, pairing window",
        f"  {settings['pairing_window_hours']:g} h.",
        "",
        "## Badly recorded batches",
        "",
        "A batch with a mis-keyed sample time or a hole in the historian must be flagged, not",
        "answered. Counted: how often a number came back where none should.",
        "",
        "| Problem | Batches | Numbers that should not exist |",
        "|---|---|---|",
        f"| Sample time keyed in as the previous sample's | {bad['mis_keyed_sample']['batches']} | "
        f"IVCD or qP answered: {bad['mis_keyed_sample']['culture_metrics_answered']}; titer finding "
        f"answered: {bad['mis_keyed_sample']['titer_findings_answered']} |",
        f"| No historian values over the harvest sample | {bad['historian_gap']['batches']} | "
        f"harvest mass answered: {bad['historian_gap']['harvest_mass_answered']}; yield finding "
        f"answered: {bad['historian_gap']['yield_findings_answered']} |",
        "",
        f"The Protein A recovery, which rests on pool measurements only, was still answered for "
        f"{bad['protein_a_recovery_answered']} of {bad['batches']} of these batches.",
        "",
        "## Titer divergence",
        "",
        '"Found" means the finding named a sample at which the titer left the reference\'s. For a',
        "batch with no culture change that is a false alarm; for a batch whose productivity fell,",
        "a detection. The delay is the culture day found minus the day the change truly began.",
        "",
        "| Tolerance | False alarms (no culture change) | Detections (productivity fell) |",
        "|---|---|---|",
    ]
    for row in result["titer_divergence"]:
        quiet, changed = row["without_culture_change"], row["with_culture_change"]
        lines.append(
            f"| {row['tolerance_percent']:g} % | {_share(quiet['found'], quiet['comparisons'])} | "
            f"{_share(changed['found'], changed['comparisons'])} |"
        )
    lines += [
        "",
        "Detections by how far productivity fell:",
        "",
        "| Tolerance | qP falls to | Detected | Delay in days: median (range) | Found before it began |",
        "|---|---|---|---|---|",
    ]
    for row in result["titer_divergence"]:
        for item in row["by_qp_factor"]:
            lines.append(
                f"| {row['tolerance_percent']:g} % | {100 * item['qp_factor']:g} % | "
                f"{_share(item['found'], item['comparisons'])} | {_days(item['delay_days'])} | "
                f"{item['found_before_onset']} |"
            )
    lines += [
        "",
        "## Step recovery shortfall",
        "",
        "The Protein A recovery finding, by the batch's true recovery, and its false alarms on",
        "batches with no Protein A loss. The harvest-to-load yield never truly changes in the",
        "generator (about 93 % in every batch), so every yield finding is a false alarm: it",
        "measures how much one titer result's assay noise moves the computed yield.",
        "",
        "| Tolerance | Protein A: false alarms | "
        + " | ".join(f"Recovery {100 * level:g} %" for level in settings["recoveries"])
        + " | Yield: false alarms |",
        "|---|---|" + "---|" * len(settings["recoveries"]) + "---|",
    ]
    for row in result["recovery_shortfall"]:
        quiet, alarms = row["protein_a_without_loss"], row["yield_false_alarms"]
        levels = " | ".join(
            _share(item["found"], item["comparisons"]) for item in row["protein_a_by_true_recovery"]
        )
        lines.append(
            f"| {row['tolerance_points']:g} points | {_share(quiet['found'], quiet['comparisons'])} | "
            f"{levels} | {_share(alarms['found'], alarms['comparisons'])} |"
        )
    lines += [
        "",
        "## Calculation error",
        "",
        "Each computed metric against the generator's true value, as a percentage of the true",
        "value, over the batches whose records are good. The error is the generator's assay",
        "noise passing through the formula; it is not a statement about any real assay.",
        "",
        "| Metric | Batches | Mean absolute error | Largest error |",
        "|---|---|---|---|",
    ]
    for metric, item in result["calculation_error_percent"].items():
        lines.append(
            f"| `{metric}` | {item['batches']} | {item['mean_abs']:.2f} % | {item['max_abs']:.2f} % |"
        )
    lines += [
        "",
        "## Known limitations",
        "",
        "- One generator, varied in three ways. Faults it does not make (a contamination, a feed",
        "  error with a different signature, a drifting sensor, a slow loss of resin capacity) are",
        "  not tested.",
        "- Normal batches differ only by the generator's own variability (peak cell density 3 %,",
        "  growth rate 2 %, productivity 2 %) and assay noise. Real batch-to-batch variation is",
        "  larger and differently shaped, and would raise the false alarms.",
        "- A finding compares with one reference batch. The spread over references is inside the",
        "  counts above but is not shown per reference.",
        '- "Detected" means a divergence was named, not that its cause was identified. The app',
        "  attributes no cause.",
        "- Only two kinds of bad records are made. Other kinds (a wrong unit, a result entered",
        "  twice, a clock offset between systems) are covered by unit tests, not by this benchmark.",
        "",
    ]
    return "\n".join(lines)
